export function getExercise(id: string): Exercise | undefined {
  return EXERCISE_LIBRARY.find((e) => e.id === id)
}

export function exercisesForMuscleGroup(group: MuscleGroup, equipment: Equipment): Exercise[] {
  return EXERCISE_LIBRARY.filter((e) => e.muscleGroup === group && e.equipment.includes(equipment))
}

export function alternativesFor(exerciseId: string, equipment: Equipment): Exercise[] {
  const current = getExercise(exerciseId)
  if (!current) return []
  return EXERCISE_LIBRARY.filter(
    (e) => e.id !== exerciseId && e.muscleGroup === current.muscleGroup && e.equipment.includes(equipment),
  )
}
